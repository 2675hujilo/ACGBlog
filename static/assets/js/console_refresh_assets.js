/* ============================================================================
 * console_refresh_assets.js —— 管理看板「一键刷新静态打包与缓存」（Bug14）
 * ----------------------------------------------------------------------------
 * 适用页面：管理员看板（存在按钮 #btn-refresh-assets，data-url 指向刷新接口）。
 *
 * 功能流程：
 *   1. 点击按钮先弹确认框（moeConfirm），说明会重新压缩 CSS/JS、写新版本号、
 *      清空服务端缓存；
 *   2. 确认后禁用按钮、改文案，POST 到 data-url（带 CSRF token）；
 *   3. 成功 → toast 提示并在约 750ms 后重载页面，让新资源生效；
 *      失败 → toast 报错并恢复按钮可点；
 *      网络异常 → 同样恢复按钮，避免按钮永久禁用。
 *
 * 依赖：moeToast / moeConfirm（萌系弹窗，缺失时降级直接执行）。
 * 安全：POST 必须带 X-CSRFToken，且接口要求管理员权限（后端校验）。
 * ----------------------------------------------------------------------------
 * 排错速查：
 *   · 接口为按钮 data-url 指向的看板刷新端点（POST，管理员 + CSRF），后端会
 *     重新压缩静态资源、写缓存版本号、清空服务端缓存；
 *   · 成功后约 750ms 才 reload，留出 toast 展示与后端写盘时间；
 *   · 失败 / 网络异常都要恢复 disabled 与原文案，否则按钮会永久不可点；
 *   · moeConfirm / moeToast 缺失时分别降级为「直接执行 / 无提示」，保证主流程；
 *   · 该操作会让全站静态缓存版本变化、所有用户下次加载取新资源，属预期；
 *   · 相关文件：refresh_assets 管理命令（同一套打包逻辑的命令行入口）、
 *     cache_bump（缓存版本号）、看板模板与后端刷新视图。
 *   · 注意：频繁执行会增加一次性 CPU（压缩）开销，建议发布静态资源后再使用。
 * ============================================================================ */
//> 该行执行对应的脚本逻辑（结合上下文理解）
(function () {
    //> 该行执行对应的脚本逻辑（结合上下文理解）
    'use strict';

    //> 声明变量「btn」（btn），用于保存对应数据，保存 DOM/窗口相关对象
    var btn = document.getElementById('btn-refresh-assets');
    //> 条件判断：满足括号内条件时执行对应分支
    if (!btn) return;

    /** 从 cookie 读取 CSRF token（Django 约定名 csrftoken）。 */
    // =========================================================
    // 【函数】csrf
    // 功能：处理「csrf」相关逻辑（console_refresh_assets）
    // 参数：无
    // 返回：无显式返回值（undefined），多以副作用（DOM/事件）为主
    // 注意：保持纯原生实现；修改时勿影响其它已初始化逻辑
    // =========================================================
    function csrf() {
        //> 声明变量「m」（m），用于保存对应数据，保存 DOM/窗口相关对象
        var m = document.cookie.match(/csrftoken=([^;]+)/);
        //> 返回结果并结束当前函数
        return m ? m[1] : '';
    //> 闭合/分隔符：结束当前代码块或回调作用域，需与开头括号正确配对
    }

    /** 执行刷新请求。 */
    // =========================================================
    // 【函数】run
    // 功能：处理「run」相关逻辑（console_refresh_assets）
    // 参数：无
    // 返回：无显式返回值（undefined），多以副作用（DOM/事件）为主
    // 注意：保持纯原生实现；修改时勿影响其它已初始化逻辑
    // =========================================================
    function run() {
        // 禁用按钮并缓存原文案，便于失败时还原
        //> 给「btn.disabled」赋值，更新其保存的状态
        btn.disabled = true;
        //> 声明变量「oldText」（old text），用于保存对应数据
        var oldText = btn.textContent;
        //> 读写纯文本内容，不解析 HTML，可防 XSS
        btn.textContent = '♻️ 正在打包刷新…';

        //> 条件判断：满足括号内条件时执行对应分支
        if (window.moeToast) {
            //> 调用函数「moeToast」并传入参数执行对应逻辑
            moeToast('正在重新压缩静态资源并清空缓存，请稍候喵~', 'info');
        //> 闭合/分隔符：结束当前代码块或回调作用域，需与开头括号正确配对
        }

        // 发起 POST：带 CSRF 头、同源凭证（cookie）
        //> 发起网络请求，返回 Promise；需处理响应与异常，并携带 CSRF
        fetch(btn.dataset.url, {
            //> 该行执行对应的脚本逻辑（结合上下文理解）
            method: 'POST',
            //> 该行执行对应的脚本逻辑（结合上下文理解）
            headers: { 'X-CSRFToken': csrf() },
            //> 该行执行对应的脚本逻辑（结合上下文理解）
            credentials: 'same-origin'
        //> 闭合/分隔符：结束当前代码块或回调作用域，需与开头括号正确配对
        })
        //> 该行执行对应的脚本逻辑（结合上下文理解）
        .then(function (resp) { return resp.json(); })
        //> 该行执行对应的脚本逻辑（结合上下文理解）
        .then(function (data) {
            //> 条件判断：满足括号内条件时执行对应分支
            if (data.ok) {
                // 成功：提示后重载页面
                //> 条件判断：满足括号内条件时执行对应分支
                if (window.moeToast) {
                    //> 调用函数「moeToast」并传入参数执行对应逻辑
                    moeToast('静态资源已刷新，正在重载页面喵~', 'success');
                //> 闭合/分隔符：结束当前代码块或回调作用域，需与开头括号正确配对
                }
                //> 设置延时执行的定时器，返回可清除的定时器 id
                setTimeout(function () { location.reload(); }, 750);
            //> 以上条件都不满足时执行的兜底分支
            } else {
                // 业务失败：报错并恢复按钮
                //> 条件判断：满足括号内条件时执行对应分支
                if (window.moeToast) {
                    //> 调用函数「moeToast」并传入参数执行对应逻辑
                    moeToast('刷新失败：' + (data.error || ''), 'error');
                //> 闭合/分隔符：结束当前代码块或回调作用域，需与开头括号正确配对
                }
                //> 给「btn.disabled」赋值，更新其保存的状态
                btn.disabled = false;
                //> 读写纯文本内容，不解析 HTML，可防 XSS
                btn.textContent = oldText;
            //> 闭合/分隔符：结束当前代码块或回调作用域，需与开头括号正确配对
            }
        //> 闭合/分隔符：结束当前代码块或回调作用域，需与开头括号正确配对
        })
        //> 该行执行对应的脚本逻辑（结合上下文理解）
        .catch(function () {
            // 网络异常：提示并恢复按钮
            //> 条件判断：满足括号内条件时执行对应分支
            if (window.moeToast) moeToast('刷新请求失败喵~', 'error');
            //> 给「btn.disabled」赋值，更新其保存的状态
            btn.disabled = false;
            //> 读写纯文本内容，不解析 HTML，可防 XSS
            btn.textContent = oldText;
        //> 闭合/分隔符：结束当前代码块或回调作用域，需与开头括号正确配对
        });
    //> 闭合/分隔符：结束当前代码块或回调作用域，需与开头括号正确配对
    }

    // 点击：有确认框则先确认，没有则直接执行
    //> 绑定「click」事件监听器，事件触发时执行回调（passive 可提升滚动性能）
    btn.addEventListener('click', function () {
        //> 条件判断：满足括号内条件时执行对应分支
        if (window.moeConfirm) {
            //> 调用函数「moeConfirm」并传入参数执行对应逻辑
            moeConfirm({
                //> 该行执行对应的脚本逻辑（结合上下文理解）
                title: '一键刷新静态与缓存？',
                //> 该行执行对应的脚本逻辑（结合上下文理解）
                message: '将重新压缩全部 CSS/JS、写入新版本号并清空服务端缓存，' +
                         //> 该行执行对应的脚本逻辑（结合上下文理解）
                         '完成后页面自动重载喵~',
                //> 该行执行对应的脚本逻辑（结合上下文理解）
                confirmText: '开始刷新'
            //> 该行执行对应的脚本逻辑（结合上下文理解）
            }).then(function (ok) {
                //> 条件判断：满足括号内条件时执行对应分支
                if (ok) run();
            //> 闭合/分隔符：结束当前代码块或回调作用域，需与开头括号正确配对
            });
        //> 以上条件都不满足时执行的兜底分支
        } else {
            //> 调用函数「run」并传入参数执行对应逻辑
            run();
        //> 闭合/分隔符：结束当前代码块或回调作用域，需与开头括号正确配对
        }
    //> 闭合/分隔符：结束当前代码块或回调作用域，需与开头括号正确配对
    });
//> 闭合/分隔符：结束当前代码块或回调作用域，需与开头括号正确配对
})();
